def _set_status(message, progress):
    global status
    status = message
    libcalamares.job.setprogress(progress)


def _write_root_file(path, text):
    """Write *text* to *path*; the job runs unprivileged, the target is root-owned."""
    libcalamares.utils.host_env_process_output(["cp", "/dev/stdin", path], None, text)


def _load_upstream(path):
    spec = importlib.util.spec_from_file_location("anka_upstream_nixos_job", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _detected_vconsole(gs):
    keymap = gs.value("keyboardVConsoleKeymap")
    if not keymap:
        try:
            with open("/run/current-system/sw/share/systemd/kbd-model-map") as f:
                keymap = vconsole_keymap(gs.value("keyboardLayout"), gs.value("keyboardVariant"), f.read())
        except OSError:
            keymap = None
    if not keymap or keymap.strip() == "us":
        return None
    keymap = keymap.strip()
    # An unknown keymap would break the system build, so only keep ones loadkeys accepts.
    try:
        subprocess.check_output(["pkexec", "loadkeys", keymap], stderr=subprocess.STDOUT)
    except (subprocess.CalledProcessError, OSError) as e:
        libcalamares.utils.warning(f"loadkeys {keymap} failed, keeping the default console keymap: {e}")
        return None
    return keymap


def _collect_settings(gs, gpu, state_version):
    partitions = gs.value("partitions") or []
    root = root_partition(partitions)
    boot_loader = gs.value("bootLoader")

    settings = {
        "firmware": "efi" if gs.value("firmwareType") == "efi" else "bios",
        "boot_device": boot_loader.get("installPath") if boot_loader else None,
        "root_fs": root.get("fs"),
        "root_luks": root.get("fsName") in ("luks", "luks2"),
        "btrfs_mounts": btrfs_mount_points(partitions),
        "gpu": gpu,
        "hostname": gs.value("hostname"),
        "kb_layout": gs.value("keyboardLayout"),
        "kb_variant": gs.value("keyboardVariant"),
        "vconsole": _detected_vconsole(gs),
        "username": gs.value("username"),
        "fullname": gs.value("fullname"),
        "autologin": gs.value("autoLoginUser") is not None,
        "state_version": state_version,
    }
    if gs.value("locationRegion") and gs.value("locationZone"):
        settings["timezone"] = "{}/{}".format(gs.value("locationRegion"), gs.value("locationZone"))

    locale_conf = dict(gs.value("localeConf") or {})
    if "LANG" in locale_conf:
        settings["locale"] = locale_conf.pop("LANG").split("/")[0]
        settings["locale_extra"] = {
            k: v.split("/")[0] for k, v in locale_conf.items() if k in LOCALE_KEYS
        }
    return settings


def run():
    gs = libcalamares.globalstorage
    conf = libcalamares.job.configuration
    root_mount = gs.value("rootMountPoint")
    etc_nixos = os.path.join(root_mount, "etc/nixos")
    upstream = _load_upstream(conf["upstreamNixosJob"])

    _set_status("Detecting hardware", 0.02)
    try:
        subprocess.check_output(
            ["pkexec", "nixos-generate-config", "--root", root_mount], stderr=subprocess.STDOUT
        )
    except subprocess.CalledProcessError as e:
        output = e.output.decode("utf8", "replace") if e.output else ""
        return ("nixos-generate-config failed", output)

    hw_path = os.path.join(etc_nixos, "hardware-configuration.nix")
    with open(hw_path) as f:
        hardware = f.read()
    fixed = fix_btrfs_subvolumes(hardware, gs.value("partitions"))
    if fixed != hardware:
        _write_root_file(hw_path, fixed)

    try:
        lspci = subprocess.check_output(["lspci", "-nn"], stderr=subprocess.STDOUT).decode("utf8", "replace")
    except (subprocess.CalledProcessError, OSError) as e:
        libcalamares.utils.warning(f"lspci failed, using open-source graphics drivers: {e}")
        lspci = ""
    gpu = detect_gpu(lspci)
    libcalamares.utils.debug(f"ANKA detected graphics: {gpu}")

    _set_status("Writing the ANKA configuration", 0.05)
    state_version = ".".join(subprocess.getoutput("nixos-version").split(".")[:2])
    settings = _collect_settings(gs, gpu, state_version)
    _write_root_file(os.path.join(etc_nixos, "configuration.nix"), build_configuration(settings))
    _write_root_file(os.path.join(etc_nixos, "flake.nix"), build_flake(conf["flakeUrl"]))
    lock_file = conf.get("lockFile") or ""
    if lock_file:
        with open(lock_file) as f:
            _write_root_file(os.path.join(etc_nixos, "flake.lock"), f.read())

    try:
        subprocess.check_output(["pkexec", "chmod", "755", root_mount], stderr=subprocess.STDOUT)
    except subprocess.CalledProcessError as e:
        libcalamares.utils.warning(f"Failed to set permissions on {root_mount}: {e.output}")

    _set_status("Installing ANKA OS", 0.1)
    cmd = ["pkexec"] + upstream.generateProxyStrings() + [
        "nixos-install",
        "--no-root-passwd",
        "--root", root_mount,
        "--flake", etc_nixos + "#anka",
        "--log-format", "internal-json",
        # The chroot store lives under /tmp, which nix refuses as a build dir.
        "--option", "build-dir", "/nix/var/nix/builds",
    ]
    if not lock_file:
        cmd += ["--override-input", "anka", "path:" + conf["ankaSource"]]
    return _run_nixos_install(cmd, upstream.NixProgress())


def _run_nixos_install(cmd, progress, start=0.1, end=1.0):
    output = ""
    try:
        proc = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        for raw in iter(proc.stdout.readline, b""):
            line = raw.decode("utf-8", "replace")
            was_json = progress.handle(line)
            if not was_json:
                output += line
                libcalamares.utils.debug(f"nixos-install: {line.strip()}")
            for message in progress.log_messages:
                output += message + "\n"
                libcalamares.utils.debug(f"nixos-install: {message}")
            progress.log_messages.clear()
            libcalamares.job.setprogress(start + progress.fraction * (end - start))
        if proc.wait() != 0:
            return ("nixos-install failed", output)
    except OSError as e:
        return ("nixos-install failed", str(e))
    libcalamares.job.setprogress(end)
    return None
