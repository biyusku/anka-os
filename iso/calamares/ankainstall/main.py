def nix_str(value):
    """Quote *value* as a Nix string literal."""
    escaped = str(value).replace("\\", "\\\\").replace('"', '\\"').replace("${", "\\${")
    return '"' + escaped + '"'


def nix_list(values):
    return "[ " + " ".join(nix_str(v) for v in values) + " ]"


_LSPCI_RE = re.compile(
    r"^(?:[0-9a-f]{4}:)?(?P<bus>[0-9a-f]{2}):(?P<dev>[0-9a-f]{2})\.(?P<fn>[0-7])\s"
    r".*\[03(?:00|02|80)\]:.*\[(?P<vendor>[0-9a-f]{4}):(?P<device>[0-9a-f]{4})\]",
    re.IGNORECASE,
)

VENDOR_INTEL, VENDOR_AMD, VENDOR_NVIDIA = "8086", "1002", "10de"


def detect_gpu(lspci_output):
    """
    Pick the ANKA GPU settings from `lspci -nn` output.

    Returns a dict with "type" (an anka.gpu.type value) and, for NVIDIA,
    "open" plus PRIME bus ids for Intel+NVIDIA laptops. A discrete NVIDIA
    card wins over an AMD iGPU (most Ryzen CPUs expose one); the iGPU keeps
    working through the kernel's amdgpu driver.
    """
    gpus = []
    for line in lspci_output.splitlines():
        m = _LSPCI_RE.match(line.strip())
        if m:
            bus_id = "PCI:{}:{}:{}".format(int(m["bus"], 16), int(m["dev"], 16), int(m["fn"], 16))
            gpus.append((m["vendor"].lower(), int(m["device"], 16), bus_id))

    vendors = {vendor for vendor, _, _ in gpus}
    nvidia = [g for g in gpus if g[0] == VENDOR_NVIDIA]

    if nvidia:
        # Turing (device id 0x1e00) and newer use the open kernel modules;
        # Blackwell only works with them.
        result = {"type": "nvidia", "open": nvidia[0][1] >= 0x1E00}
        intel = [g for g in gpus if g[0] == VENDOR_INTEL]
        if intel:
            result.update(type="intel+nvidia", intelBusId=intel[0][2], nvidiaBusId=nvidia[0][2])
        return result
    if VENDOR_AMD in vendors:
        return {"type": "amd"}
    if VENDOR_INTEL in vendors:
        return {"type": "intel"}
    return {"type": "none"}  # virtual machines, unknown vendors


def root_partition(partitions):
    for part in partitions or []:
        if part.get("mountPoint") == "/":
            return part
    return {}


def btrfs_mount_points(partitions):
    """
    Mount points that end up on Btrfs. Subvolumes have no partition entry of
    their own: on a Btrfs root, mount.conf creates every subvolume whose
    mount point isn't a separate partition.
    """
    fs_by_mount = {p.get("mountPoint"): p.get("fs") for p in partitions or [] if p.get("mountPoint")}
    if fs_by_mount.get("/") == "btrfs":
        return [mp for mp in BTRFS_SUBVOLUMES if fs_by_mount.get(mp, "btrfs") == "btrfs"]
    return [mp for mp in BTRFS_SUBVOLUMES if fs_by_mount.get(mp) == "btrfs"]


def fix_btrfs_subvolumes(hardware_config, partitions):
    """
    Make the subvol= options in hardware-configuration.nix match the
    subvolumes mount.conf created (nixos-generate-config can get them wrong).
    """
    if root_partition(partitions).get("fs") != "btrfs":
        return hardware_config
    for mount_point, subvol in BTRFS_SUBVOLUMES.items():
        pattern = rf'(fileSystems\."{re.escape(mount_point)}"\s*=\s*\{{[^}}]*"subvol=)[^"]*"'
        hardware_config = re.sub(pattern, rf'\g<1>{subvol}"', hardware_config, flags=re.DOTALL)
    return hardware_config


def vconsole_keymap(layout, variant, kbd_model_map):
    """Map an X11 layout/variant to a console keymap using systemd's kbd-model-map."""
    rows = [line.split() for line in kbd_model_map.splitlines() if line.strip() and not line.startswith("#")]
    rows = [r for r in rows if len(r) >= 4 and r[1] == layout]
    if not rows:
        return None
    for row in rows:
        if (variant or "-") in row[3].split(","):
            return row[0]
    return rows[0][0]


def build_flake(flake_url):
    return f"""\
# ANKA OS — this computer's system flake (written by the ANKA installer).
#
# ANKA itself comes from the `anka` input; this machine's own settings are
# in configuration.nix and hardware-configuration.nix.
#
#   Apply changes:  sudo nixos-rebuild switch --flake /etc/nixos#anka
#   Update ANKA:    sudo anka-update apply   (or System Settings › ANKA Updates)
#                   anka-update rewrites the inputs.anka.url line below.
{{
  description = "ANKA OS";

  inputs.anka.url = {nix_str(flake_url)};

  outputs = {{ anka, ... }}: {{
    nixosConfigurations.anka = anka.lib.mkSystem {{
      modules = [
        ./hardware-configuration.nix
        ./configuration.nix
      ];
    }};
  }};
}}
"""


def build_configuration(settings):
    """
    Render configuration.nix from the installer choices.

    *settings* keys: firmware ("efi" | "bios"), boot_device, root_fs,
    root_luks, btrfs_mounts, gpu (from detect_gpu), hostname, timezone,
    locale, locale_extra (dict), kb_layout, kb_variant, vconsole,
    username, fullname, autologin, state_version.
    """
    out = [
        "# ANKA OS — this computer's settings (written by the ANKA installer).",
        "# ANKA's own defaults come from the `anka` flake input (see flake.nix);",
        "# anything set here overrides them. Apply changes with:",
        "#   sudo nixos-rebuild switch --flake /etc/nixos#anka",
        "{ config, lib, pkgs, ... }:",
        "",
        "{",
        "  # ── Boot ──────────────────────────────────────────────────────────────",
    ]
    if settings["firmware"] == "efi":
        out.append('  anka.boot.loader = "systemd-boot";')
    else:
        out.append('  anka.boot.loader = "grub";')
        out.append("  anka.boot.grubDevice = {};".format(nix_str(settings.get("boot_device") or "nodev")))
        if settings.get("root_luks"):
            out.append("  boot.loader.grub.enableCryptodisk = true;  # /boot lives on the encrypted root")

    out += ["", "  # ── Disk ──────────────────────────────────────────────────────────────"]
    root_fs = settings.get("root_fs") or "ext4"
    if root_fs in ("btrfs", "ext4", "xfs"):
        out.append(f"  anka.filesystem.rootFormat = {nix_str(root_fs)};")
    out.append("  anka.filesystem.btrfsSubvolumes = {};".format("true" if root_fs == "btrfs" else "false"))
    for mount_point in settings.get("btrfs_mounts", []):
        out.append(f"  fileSystems.{nix_str(mount_point)}.options = {nix_list(BTRFS_MOUNT_OPTIONS)};")

    gpu = settings["gpu"]
    out += ["", "  # ── Graphics (detected during installation) ───────────────────────────"]
    out.append("  anka.gpu.type = {};".format(nix_str(gpu["type"])))
    if "open" in gpu:
        out.append("  anka.gpu.nvidia.open = {};".format("true" if gpu["open"] else "false"))
    if gpu["type"] == "intel+nvidia":
        out.append("  anka.gpu.nvidia.prime = {")
        out.append("    enable      = true;")
        out.append("    intelBusId  = {};".format(nix_str(gpu["intelBusId"])))
        out.append("    nvidiaBusId = {};".format(nix_str(gpu["nvidiaBusId"])))
        out.append("  };")

    out += ["", "  # ── Network ───────────────────────────────────────────────────────────"]
    out.append("  anka.network.hostname = {};".format(nix_str(settings.get("hostname") or "anka")))

    out += ["", "  # ── Language, time and keyboard ───────────────────────────────────────"]
    if settings.get("timezone"):
        out.append("  time.timeZone = {};".format(nix_str(settings["timezone"])))
    if settings.get("locale"):
        out.append("  i18n.defaultLocale = {};".format(nix_str(settings["locale"])))
        extra = dict.fromkeys(LOCALE_KEYS, settings["locale"])
        extra.update(settings.get("locale_extra") or {})
        out.append("  i18n.extraLocaleSettings = {")
        for key in LOCALE_KEYS:
            out.append(f"    {key} = {nix_str(extra[key])};")
        out.append("  };")
    if settings.get("kb_layout"):
        out.append("  services.xserver.xkb = {")
        out.append("    layout  = {};".format(nix_str(settings["kb_layout"])))
        out.append("    variant = {};".format(nix_str(settings.get("kb_variant") or "")))
        out.append("  };")
    if settings.get("vconsole"):
        out.append("  console.keyMap = {};".format(nix_str(settings["vconsole"])))

    if settings.get("username"):
        user = settings["username"]
        out += ["", "  # ── User ──────────────────────────────────────────────────────────────"]
        out.append(f"  users.users.{nix_str(user)} = {{")
        out.append("    isNormalUser = true;")
        out.append("    description  = {};".format(nix_str(settings.get("fullname") or user)))
        out.append(f"    extraGroups  = {nix_list(USER_GROUPS)};")
        out.append("  };")
        if settings.get("autologin"):
            out.append("  anka.desktop.autoLogin = {")
            out.append("    enable = true;")
            out.append(f"    user   = {nix_str(user)};")
            out.append("  };")

    out += [
        "",
        "  # Release this machine was first installed with — do NOT change it.",
        "  system.stateVersion = {};".format(nix_str(settings["state_version"])),
        "}",
        "",
    ]
    return "\n".join(out)


