#!/usr/bin/env python3
"""
ANKA OS — Calamares job that installs ANKA.

Takes the place of the upstream `nixos` job from calamares-nixos-extensions.
Instead of a stand-alone configuration.nix it writes /etc/nixos as a small
flake that uses ANKA as an input:

  /etc/nixos/flake.nix                  anka.lib.mkSystem { ... }
  /etc/nixos/flake.lock                 ANKA pinned to the revision of this ISO
  /etc/nixos/hardware-configuration.nix from nixos-generate-config
  /etc/nixos/configuration.nix          the choices made in the installer

and then runs `nixos-install --flake /etc/nixos#anka`. Later updates move
the `anka` input forward (`anka-update`, see docs/update-system.md).

Job configuration (ankainstall.conf, generated by iso/calamares/default.nix):
  flakeUrl         flake reference of ANKA written into flake.nix
  ankaSource       store path of the ANKA tree this ISO was built from
  lockFile         flake.lock pinning ANKA to that tree ("" if the ISO was
                   built from a dirty tree; then the source is passed with
                   --override-input instead)
  upstreamNixosJob path of the upstream `nixos` job, reused for its
                   nix progress parser and proxy handling
"""

import importlib.util
import os
import re
import subprocess

import libcalamares

# Btrfs layout created by mount.conf — keep both files in sync.
BTRFS_SUBVOLUMES = {
    "/": "@",
    "/home": "@home",
    "/nix": "@nix",
    "/.snapshots": "@snapshots",
}
BTRFS_MOUNT_OPTIONS = ["compress=zstd:1", "noatime"]

USER_GROUPS = ["wheel", "networkmanager", "video", "audio", "input", "gamemode", "anka-mcp"]

LOCALE_KEYS = [
    "LC_ADDRESS", "LC_IDENTIFICATION", "LC_MEASUREMENT", "LC_MONETARY", "LC_NAME",
    "LC_NUMERIC", "LC_PAPER", "LC_TELEPHONE", "LC_TIME",
]

status = "Installing ANKA OS"


def pretty_name():
    return "Installing ANKA OS"


def pretty_status_message():
    return status


